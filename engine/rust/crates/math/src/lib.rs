pub mod approx;
/// Ergonomic, non-generic `f32`/`f64` constants. See [`consts::f32`]/
/// [`consts::f64`].
pub mod consts;
/// The internal [`Scalar`] trait every generic function in this crate is
/// written against.
pub mod scalar;

pub use scalar::Scalar;

