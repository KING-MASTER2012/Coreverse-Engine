//! Cross-language golden values shared with the C++ mirror (`cv-math`,
//! `engine/cpp/math`).
//!
//! `tests/math_golden/golden.txt` holds two kinds of lines, one per item:
//!
//! - `layout <Type> <size> <align> <field offsets...>`: the `#[repr(C)]` layout
//!   of the types the C++ side mirrors;
//! - `<name> <f32 values...>`: the result of a fixed computation (the inputs
//!   are written out in `generate()` below *and* in
//!   `tests/cpp/math_layout_test.cpp`; keep both in sync).
//!
//! This test recomputes everything with the Rust types and compares it with the
//! file, the C++ test recomputes it with the C++ types and compares it with the
//! same file, so the two implementations agree transitively. After an
//! intentional change run `UPDATE_GOLDEN=1 cargo test -p math --test cpp_golden`
//! and commit the new file.
#![allow(missing_docs)]

use std::fmt::Write as _;
use std::mem::{align_of, offset_of, size_of};

use math::{Mat4, Quat, Radians, Vec2, Vec3, Vec4};

const GOLDEN_PATH: &str = concat!(
env!("CARGO_MANIFEST_DIR"),
"/../../../../tests/math_golden/golden.txt"
);

fn floats(out: &mut String, name: &str, values: &[f32]) {
    out.push_str(name);
    for v in values {
        write!(out, " {v:?}").unwrap();
    }
    out.push('\n');
}

fn layout(out: &mut String, name: &str, size: usize, align: usize, offsets: &[usize]) {
    write!(out, "layout {name} {size} {align}").unwrap();
    for o in offsets {
        write!(out, " {o}").unwrap();
    }
    out.push('\n');
}

fn generate() -> String {
    let mut out = String::new();
    out.push_str(
        "# Generated by engine/rust/crates/math/tests/cpp_golden.rs - do not edit by hand.\n",
    );
    out.push_str("# Regenerate: UPDATE_GOLDEN=1 cargo test -p math --test cpp_golden\n");

    layout(
        &mut out,
        "Vec2",
        size_of::<Vec2>(),
        align_of::<Vec2>(),
        &[offset_of!(Vec2, x), offset_of!(Vec2, y)],
    );
    layout(
        &mut out,
        "Vec3",
        size_of::<Vec3>(),
        align_of::<Vec3>(),
        &[
            offset_of!(Vec3, x),
            offset_of!(Vec3, y),
            offset_of!(Vec3, z),
        ],
    );
    layout(
        &mut out,
        "Vec4",
        size_of::<Vec4>(),
        align_of::<Vec4>(),
        &[
            offset_of!(Vec4, x),
            offset_of!(Vec4, y),
            offset_of!(Vec4, z),
            offset_of!(Vec4, w),
        ],
    );
    layout(
        &mut out,
        "Quat",
        size_of::<Quat>(),
        align_of::<Quat>(),
        &[
            offset_of!(Quat, x),
            offset_of!(Quat, y),
            offset_of!(Quat, z),
            offset_of!(Quat, w),
        ],
    );
    layout(
        &mut out,
        "Mat4",
        size_of::<Mat4>(),
        align_of::<Mat4>(),
        &[
            offset_of!(Mat4, x_axis),
            offset_of!(Mat4, y_axis),
            offset_of!(Mat4, z_axis),
            offset_of!(Mat4, w_axis),
        ],
    );

    // ---- inputs (mirrored in tests/cpp/math_layout_test.cpp) ----
    let axis = Vec3::new(0.267_261_24, 0.534_522_5, 0.801_783_7);
    let q1 = Quat::from_axis_angle(axis, Radians::new(0.9));
    let q2 = Quat::from_rotation_y(Radians::new(-1.1));
    let srt = Mat4::from_scale_rotation_translation(
        Vec3::new(2.0, 1.0, 0.5),
        q1,
        Vec3::new(1.0, -2.0, 3.0),
    );
    let proj = Mat4::perspective_rh(Radians::new(1.047_197_6), 16.0 / 9.0, 0.1, 100.0);
    let view = Mat4::look_at_rh(
        Vec3::new(3.0, 4.0, 5.0),
        Vec3::new(0.5, -0.25, 1.0),
        Vec3::new(0.0, 1.0, 0.0),
    );

    floats(&mut out, "mat4_perspective_rh", &proj.to_cols_array());
    floats(&mut out, "mat4_look_at_rh", &view.to_cols_array());
    floats(
        &mut out,
        "mat4_rotation_x",
        &Mat4::from_rotation_x(Radians::new(0.7)).to_cols_array(),
    );
    floats(
        &mut out,
        "mat4_rotation_y",
        &Mat4::from_rotation_y(Radians::new(-1.1)).to_cols_array(),
    );
    floats(
        &mut out,
        "mat4_rotation_z",
        &Mat4::from_rotation_z(Radians::new(2.3)).to_cols_array(),
    );
    floats(
        &mut out,
        "mat4_axis_angle",
        &Mat4::from_axis_angle(axis, Radians::new(0.9)).to_cols_array(),
    );
    floats(
        &mut out,
        "mat4_translation",
        &Mat4::from_translation(Vec3::new(1.0, -2.0, 3.0)).to_cols_array(),
    );
    floats(
        &mut out,
        "mat4_scale",
        &Mat4::from_scale(Vec3::new(2.0, 1.0, 0.5)).to_cols_array(),
    );
    floats(
        &mut out,
        "mat4_from_quat",
        &Mat4::from_quat(q1).to_cols_array(),
    );
    floats(&mut out, "mat4_srt", &srt.to_cols_array());
    floats(&mut out, "mat4_mvp", &(proj * view * srt).to_cols_array());
    floats(
        &mut out,
        "mat4_inverse_srt",
        &srt.inverse().expect("srt is invertible").to_cols_array(),
    );
    floats(
        &mut out,
        "mat4_transpose_srt",
        &srt.transpose().to_cols_array(),
    );
    floats(&mut out, "quat_from_axis_angle", &q1.to_array());
    floats(&mut out, "quat_mul", &q1.mul_quat(q2).to_array());
    floats(&mut out, "quat_slerp", &q1.slerp(q2, 0.3).to_array());
    floats(
        &mut out,
        "quat_normalize",
        &Quat::new(1.0, 2.0, 3.0, 4.0).normalize().to_array(),
    );
    floats(
        &mut out,
        "quat_rotate_vec3",
        &q1.mul_vec3(Vec3::new(1.0, 2.0, 3.0)).to_array(),
    );
    floats(
        &mut out,
        "vec3_cross",
        &Vec3::new(1.0, 2.0, 3.0)
            .cross(Vec3::new(-2.0, 0.5, 4.0))
            .to_array(),
    );
    floats(
        &mut out,
        "vec3_normalize",
        &Vec3::new(3.0, 4.0, 12.0).normalize().to_array(),
    );
    floats(
        &mut out,
        "vec3_dot",
        &[Vec3::new(1.0, 2.0, 3.0).dot(Vec3::new(-2.0, 0.5, 4.0))],
    );
    floats(
        &mut out,
        "mat4_transform_point3",
        &srt.transform_point3(Vec3::new(1.0, 1.0, 1.0)).to_array(),
    );
    floats(
        &mut out,
        "mat4_project_point3",
        &(proj * view).project_point3(Vec3::ZERO).to_array(),
    );
    out
}

/// Layout lines must match exactly, value lines within a small tolerance (the
/// last digit of `sin`/`cos` may differ between platforms' libm).
fn compare(actual: &str, expected: &str) -> Result<(), String> {
    let a_lines: Vec<&str> = actual.lines().filter(|l| !l.starts_with('#')).collect();
    let e_lines: Vec<&str> = expected.lines().filter(|l| !l.starts_with('#')).collect();
    if a_lines.len() != e_lines.len() {
        return Err(format!(
            "{} lines computed, {} in the golden file",
            a_lines.len(),
            e_lines.len()
        ));
    }
    for (a, e) in a_lines.iter().zip(&e_lines) {
        let at: Vec<&str> = a.split_whitespace().collect();
        let et: Vec<&str> = e.split_whitespace().collect();
        if at.len() != et.len() || at[0] != et[0] {
            return Err(format!("line mismatch:\n  computed: {a}\n  golden:   {e}"));
        }
        let is_layout = at[0] == "layout";
        for (x, y) in at.iter().zip(&et).skip(1) {
            if is_layout {
                if x != y {
                    return Err(format!(
                        "layout mismatch:\n  computed: {a}\n  golden:   {e}"
                    ));
                }
                continue;
            }
            let xv: f64 = x.parse().unwrap();
            let yv: f64 = y.parse().unwrap();
            if (xv - yv).abs() > 1e-5 * (1.0 + yv.abs()) {
                return Err(format!("value mismatch in `{}`: {xv} vs {yv}", at[0]));
            }
        }
    }
    Ok(())
}

#[test]
fn matches_golden_file() {
    let actual = generate();
    if std::env::var_os("UPDATE_GOLDEN").is_some() {
        std::fs::write(GOLDEN_PATH, &actual).expect("write golden file");
        return;
    }
    let expected = std::fs::read_to_string(GOLDEN_PATH)
        .expect("tests/math_golden/golden.txt (run with UPDATE_GOLDEN=1)");
    if let Err(message) = compare(&actual, &expected) {
        panic!(
            "{message}\n\nRegenerate with: UPDATE_GOLDEN=1 cargo test -p math --test cpp_golden"
        );
    }
}
