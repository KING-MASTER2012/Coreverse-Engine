//! `platform` — the operating-system abstraction of the Coreverse Engine.
//!
//! The crate sits directly above [`ccore`] and has no other engine
//! dependencies. It is built in phases; what exists today:
//!
//! * [`info`] — OS name and version, CPU core counts, installed memory and the
//!   session's display server, plus [`SystemInfo`](info::SystemInfo) to collect
//!   all of it.
//! * [`time`] — monotonic and wall clocks, [`Stopwatch`](time::Stopwatch),
//!   [`FrameTimer`](time::FrameTimer), a [`FixedStep`](time::FixedStep)
//!   accumulator and [`precise_sleep`](time::precise_sleep). The timers are
//!   generic over a [`TimeSource`](time::TimeSource), so tests do not need
//!   the real clock.
//! * [`paths`] — [`AppDirs`](paths::AppDirs): the config, data, cache, log and
//!   temp directories of an application, plus the home and executable
//!   directories, as `Utf8PathBuf`s. Nothing is created unless asked.
//! * [`env`](mod@env) — read-only environment access (`var`, `var_path`, `var_bool`,
//!   `args`, `current_dir`); there is deliberately no way to set variables.
//! * [`process`] — process id, executable path, `open_url` and
//!   `reveal_in_file_manager` (desktop only).
//! * [`thread`] — OS-level thread names and abstract
//!   [`ThreadPriority`](thread::ThreadPriority) levels.
//! * [`support`] — which of those features works how well on which platform.
//! * [`error`] — [`PlatformError`], convertible into [`ccore::CoreError`].
//! * [`window`] — windows and the application lifecycle: the callback-based
//!   [`App`](window::App), [`WindowDesc`](window::WindowDesc),
//!   [`WindowEvent`](window::WindowEvent) (surface lost/created included),
//!   [`NativeWindowHandle`](window::NativeWindowHandle) and a headless backend
//!   that needs no display. The desktop (`winit`) and mobile backends and
//!   input handling are planned as further phases.
//!
//! [`Platform`], [`Architecture`] and [`Endian`] are re-exported from
//! [`ccore::platform`] (the compile-time tags stay there), and [`PlatformExt`]
//! adds `is_desktop`/`is_mobile`/`is_unix` to [`Platform`].
//!
//! # Platform support
//!
//! Targets: Linux, macOS, Windows, Android and iOS. Anything else compiles and
//! reports [`PlatformError::Unsupported`]; so do the standard directories on
//! Android and iOS. The table is generated by
//! [`support::support`], which is the source of truth.
//!
//! | Feature          | Windows | Linux   | macOS | Android | iOS  |
//! | :--------------- | :-----: | :-----: | :---: | :-----: | :--: |
//! | OS version       | full    | full    | full  | partial | full |
//! | Logical cores    | full    | full    | full  | full    | full |
//! | Physical cores   | full    | partial | full  | partial | full |
//! | Total memory     | full    | full    | full  | full    | full |
//! | Display server   | full    | partial | full  | full    | full |
//! | Clocks           | full    | full    | full  | full    | full |
//! | Precise sleep    | full    | full    | full  | full    | full |
//! | Standard dirs    | full    | full    | full  | unsupported | unsupported |
//! | Environment      | full    | full    | full  | full    | full |
//! | Open URL         | full    | partial | full  | unsupported | unsupported |
//! | Reveal in files  | full    | partial | full  | unsupported | unsupported |
//! | Thread name      | full    | full    | full  | partial | partial |
//! | Thread priority  | full    | partial | full  | partial | partial |
//!
//! "Partial" means best effort: Android reports the kernel release when the
//! version property is missing, physical cores come from sysfs (hidden in some
//! containers and Android builds), and on Linux the display server is derived
//! from environment variables. Precise sleep is a sleep plus a short spin;
//! on Windows older than 10 1803 (no high-resolution timer) it may overshoot
//! by the system timer granularity but never wakes early. On Linux, `open_url` and `reveal_in_file_manager` need `xdg-open`
//! (the latter only opens the folder), and raising a thread's priority needs
//! privileges (`PermissionDenied` otherwise). Android and iOS are compile-checked in CI only;
//! no code in this crate has been run on a device.
//!
//! # `unsafe`
//!
//! The workspace denies `unsafe_code`. The only exception is the private `sys`
//! module, which wraps the few OS calls std does not expose (`uname`,
//! `sysconf`, `sysctlbyname`, kernel32/ntdll, the Windows waitable timer,
//! `SHGetKnownFolderPath`) in safe functions.

